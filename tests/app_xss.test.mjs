const baselineSource = await readFile(new URL('./baseline/audithor_project/static/js/app.js', import.meta.url), 'utf8');
const emptyState = text => text.match(/const createInitialEmptyState = \(\) => `(.*?)`;/s)?.[1];
assert.equal(emptyState(source), emptyState(baselineSource), 'benign empty-state markup remains unchanged');
const helperSource = source.match(/export const isPlainObject = .*?\nexport const validateImportShape = .*?;/s)?.[0];
assert.ok(helperSource);
const validators = new Function(`${helperSource.replaceAll('export const', 'const')}\nreturn { isPlainObject, isValidScopeData, isImportFileSizeAllowed, validateImportShape };`)();
assert.equal(validators.validateImportShape(null), false);
assert.equal(validators.validateImportShape({ metadata: [], results: {} }), false);
assert.equal(validators.validateImportShape({ metadata: {}, results: [] }), false);
assert.equal(validators.isValidScopeData(null), false);
assert.equal(validators.isValidScopeData([]), false);
assert.equal(validators.isValidScopeData({ arn: null }), false);
assert.equal(validators.isValidScopeData({ arn: { comment: 'in scope' } }), true);
assert.equal(validators.isImportFileSizeAllowed(200 * 1024 * 1024 + 1), false);
assert.equal(validators.isImportFileSizeAllowed(200 * 1024 * 1024), true);
assert.equal(validators.validateImportShape({ metadata: {}, results: {} }), true);

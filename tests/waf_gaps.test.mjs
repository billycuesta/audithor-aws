import { JSDOM } from 'jsdom';
import assert from 'node:assert/strict';
const { window } = new JSDOM('<div id="waf-view"></div>');
globalThis.window = window;
globalThis.document = window.document;
window.securityHubApiData = {results:{findings:{wafFindings:[]}}};
window.wafApiData = {metadata:{executionDate:'today'},results:{acls:[{Name:'web',Scope:'REGIONAL',Region:'us-east-1',AssociatedResourceArns:[],DefaultAction:{Allow:{}},Capacity:17,Rules:[{Name:'second',Priority:2,Action:{Block:{}},StatementSummary:'second statement'},{Name:'<img src=x onerror=alert(1)>',Priority:1,Action:{Block:{}},StatementSummary:'ManagedRuleGroupStatement AWS/CommonRuleSet'}]},{Name:'empty',Scope:'REGIONAL',Region:'us-east-1',AssociatedResourceArns:[],DefaultAction:{Block:{CustomResponse:{ResponseCode:403}}},Capacity:0,Rules:[]}],ip_sets:[]}};
const root = new URL('../audithor/static/js/views/', import.meta.url).href;
const view = await import(root+'05_waf.js');
view.buildWafView();
const el = document.getElementById('waf-view');
assert.match(el.textContent,/Allow/);
assert.match(el.textContent,/17/);
assert.match(el.textContent,/ManagedRuleGroupStatement AWS\/CommonRuleSet/);
assert.equal(el.querySelector('img'),null);
const webRow = [...el.querySelectorAll('tbody tr')].find(row => row.cells[0]?.textContent === 'web');
const rules = webRow.cells[9];
assert.deepEqual([...rules.querySelectorAll('tr')].filter(row => row.cells[1]?.textContent !== 'Name').map(row => row.cells[1].textContent), ['<img src=x onerror=alert(1)>', 'second']);
const emptyRow = [...el.querySelectorAll('tbody tr')].find(row => row.cells[0]?.textContent === 'empty');
assert.match(emptyRow.cells[7].textContent,/Block \(custom response 403\)/);
assert.equal(emptyRow.cells[9].textContent,'None');
window.wafApiData = {metadata:{executionDate:'today'},results:{acls:[{Name:'old',Scope:'REGIONAL',Region:'us-east-1'}],ip_sets:[]}};
view.buildWafView();
const oldRow = [...el.querySelectorAll('tbody tr')].find(row => row.cells[0]?.textContent === 'old');
assert.equal(oldRow.cells[7].textContent,'Not collected');
assert.equal(oldRow.cells[8].textContent,'Not collected');
assert.equal(oldRow.cells[9].textContent,'Not collected');
console.log('WAF gaps view checks passed');

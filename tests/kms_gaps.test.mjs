import { JSDOM } from 'jsdom';
import assert from 'node:assert/strict';
const { window } = new JSDOM('<div id="kms-secrets-view"></div>');
globalThis.window = window;
globalThis.document = window.document;
window.scopedResources = {};
window.secretsManagerApiData = null;
window.kmsApiData = {metadata: {executionDate: '2026-01-01'}, results: {keys: [{Region: 'us-east-1', KeyId: 'key-1', ARN: 'arn:key', Aliases: 'alias/test', Status: 'Enabled', Origin: 'AWS_KMS', KeyManager: 'CUSTOMER', RotationEnabled: 'Enabled', Policy: {}, KeySpec: '<img src=x onerror=alert(1)>', KeyUsage: 'ENCRYPT_DECRYPT', EncryptionAlgorithms: ['SYMMETRIC_DEFAULT'], Enrichment: {keyMetadata: {status: 'complete'}}}]}};
const root = new URL('../audithor/static/js/views/', import.meta.url).href;
const view = await import(root + '12_kms_secrets.js');
view.buildKmsSecretsView();
let container = document.getElementById('kms-secrets-view');
assert.match(container.textContent, /Key Spec/);
assert.match(container.textContent, /ENCRYPT_DECRYPT/);
assert.match(container.textContent, /SYMMETRIC_DEFAULT/);
assert.match(container.textContent, /<img src=x onerror=alert\(1\)>/);
assert.equal(container.querySelector('img'), null);
window.kmsApiData.results.keys[0] = {Region:'us-east-1', KeyId:'old', ARN:'arn:old', Aliases:'old', Status:'Enabled', KeyManager:'CUSTOMER', RotationEnabled:'N/A', Policy:{}};
view.buildKmsSecretsView();
container = document.getElementById('kms-secrets-view');
assert.match(container.textContent, /Not collected/);
window.kmsApiData.results.keys = [{Region:'us-east-1', KeyId:'failed-key', ARN:'arn:failed', Aliases:'alias/failed', Status:null, KeyManager:null, RotationEnabled:'N/A', Enrichment:{keyMetadata:{status:'failed'}}}];
view.buildKmsSecretsView();
container = document.getElementById('kms-secrets-view');
const failedRow = [...container.querySelectorAll('tr')].find(row => row.textContent.includes('failed-key'));
assert.ok(failedRow);
assert.match(failedRow.textContent, /Unknown/);
assert.match(failedRow.textContent, /Not collected/);
assert.doesNotMatch(failedRow.textContent, /AWS/);
console.log('KMS metadata view checks passed');

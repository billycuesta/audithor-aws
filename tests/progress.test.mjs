import assert from 'node:assert/strict';
import { JSDOM } from 'jsdom';
import { formatBar, createProgressTracker, formatElapsed, formatProgressLine, formatRunning, renderProgress, hideProgress } from '../audithor/static/js/progress.js';

assert.equal(formatBar(0, 21), '░'.repeat(20));
assert.equal(formatBar(1, 21), '█░'.padEnd(20, '░'));
assert.equal(formatBar(9, 21), '█████████░'.padEnd(20, '░'));
assert.equal(formatBar(21, 21), '█'.repeat(20));
assert.equal(formatBar(1, 3, 10), '███░░░░░░░');
assert.equal(formatBar(-1, 2, 10), '░'.repeat(10));
assert.equal(formatBar(3, 2, 10), '█'.repeat(10));
assert.equal(formatBar(1, 0), '░'.repeat(20));
assert.equal(formatBar(NaN, 2), '░'.repeat(20));
let time = 100;
const tracker = createProgressTracker(['a', 'b', 'c'], () => time);
time = 125;
tracker.start('b'); tracker.start('a'); tracker.start('b');
tracker.finish('c', false); tracker.finish('c', true); tracker.finish('b');
assert.deepEqual(tracker.snapshot(), { done: 2, total: 3, percent: 67, running: ['a'], failed: ['c'], elapsedMs: 25 });
const successThenFailure = createProgressTracker(['a'], () => 0);
successThenFailure.finish('a', true);
successThenFailure.finish('a', false);
assert.deepEqual(successThenFailure.snapshot(), { done: 1, total: 1, percent: 100, running: [], failed: [], elapsedMs: 0 });
const failureThenSuccess = createProgressTracker(['a'], () => 0);
failureThenSuccess.finish('a', false);
failureThenSuccess.finish('a', true);
assert.deepEqual(failureThenSuccess.snapshot(), { done: 1, total: 1, percent: 100, running: [], failed: ['a'], elapsedMs: 0 });
const startOrder = createProgressTracker(['a', 'b'], () => 0);
startOrder.start('a'); startOrder.start('b'); startOrder.start('a');
assert.deepEqual(startOrder.snapshot().running, ['a', 'b']);
const finishUnstarted = createProgressTracker(['a', 'b'], () => 0);
finishUnstarted.finish('b');
assert.deepEqual(finishUnstarted.snapshot(), { done: 1, total: 2, percent: 50, running: [], failed: [], elapsedMs: 0 });
assert.throws(() => tracker.start('x'), { message: 'Unknown task: x' });
assert.throws(() => tracker.finish('x'), { message: 'Unknown task: x' });
assert.equal(formatElapsed(0), '00:00');
assert.equal(formatElapsed(59000), '00:59');
assert.equal(formatElapsed(60000), '01:00');
assert.equal(formatElapsed(4503000), '75:03');
assert.equal(formatElapsed(-1), '00:00');
assert.equal(formatElapsed(NaN), '00:00');
const snap = { done: 5, total: 21, percent: 24, failed: ['x'], elapsedMs: 12000, running: ['a', 'b', 'c', 'd'] };
assert.equal(formatProgressLine(snap), `${'█'.repeat(5)}${'░'.repeat(15)} 5/21 (24%) · 1 failed · 00:12`);
assert.equal(formatProgressLine({ ...snap, failed: [] }), `${'█'.repeat(5)}${'░'.repeat(15)} 5/21 (24%) · 00:12`);
assert.equal(formatRunning(snap), 'Running: a, b, c +1 more');
assert.equal(formatRunning(snap, x => x.toUpperCase(), 2), 'Running: A, B +2 more');
assert.equal(formatRunning({ running: [] }), '');
const { window } = new JSDOM('<div id="root" class="hidden"><span data-scan-progress-bar></span><span data-scan-progress-detail></span></div>');
const root = window.document.getElementById('root');
renderProgress(root, snap, n => n === 'a' ? '<img src=x onerror=alert(1)>' : n);
assert.equal(root.querySelector('[data-scan-progress-bar]').textContent, formatProgressLine(snap));
assert.equal(root.querySelector('[data-scan-progress-detail]').textContent, 'Running: <img src=x onerror=alert(1)>, b, c +1 more');
assert.equal(root.querySelectorAll('img').length, 0);
assert.equal(root.getAttribute('aria-valuenow'), '24');
assert.equal(root.getAttribute('aria-valuemin'), '0');
assert.equal(root.getAttribute('aria-valuemax'), '100');
assert.equal(root.getAttribute('aria-valuetext'), '5 of 21 collectors finished');
assert.equal(root.classList.contains('hidden'), false);
hideProgress(root); assert.equal(root.classList.contains('hidden'), true);
renderProgress(null, snap); hideProgress(null);
const sparse = window.document.createElement('div'); renderProgress(sparse, snap); assert.equal(sparse.getAttribute('aria-valuenow'), '24');
console.log('Progress formatting, tracking, and safe DOM rendering checks passed');
